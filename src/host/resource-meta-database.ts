/**
 * 获取资源元信息
 * @param id 资源ID（包名）
 * @returns 资源元信息，如果不存在返回 null
 */
export function getResourceMeta(id: string): ResourceMeta | null {
  return PLUGIN_META_DATABASE[id] || null;
}

/**
 * 获取资源描述（优先使用数据库中的描述，其次使用传入的描述）
 * @param id 资源ID
 * @param fallbackDescription 备用描述
 * @returns 最终描述
 */
export function getResourceDescription(id: string, fallbackDescription: string = ''): string {
  const meta = PLUGIN_META_DATABASE[id];
  if (meta && meta.description) {
    return meta.description;
  }
  return fallbackDescription || '暂无描述';
}

